/**
 * Как показывать телеграм-ссылку человеку.
 *
 * Голый `https://t.me/matebox` под QR-кодом читается как строка из адресной
 * строки, а не как имя канала. В самом телеграме это имя выглядит `@matebox`,
 * им же ищут — значит подпись должна выглядеть так же.
 *
 * Подпись считается из адреса, а не пишется рядом с ним: два поля рядом
 * разъезжаются на первой правке, а адрес правит заказчик.
 */

/**
 * @returns `@name` для публичного канала или бота, `t.me/+…` для ссылки-
 *   приглашения — у неё имени нет и придумывать его нельзя. Всё, что не
 *   похоже на t.me, возвращается без схемы: пусть будет видно, что это
 *   не телеграм, а не подделано под него.
 */
export function telegramLabel(url: string): string {
  const bare = url.replace(/^https?:\/\//, '').replace(/\/$/, '');
  const match = bare.match(/^t\.me\/([A-Za-z0-9_]{4,})$/);
  return match ? `@${match[1]}` : bare;
}
