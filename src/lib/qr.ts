/**
 * QR-код ссылки — строится на сборке, а не лежит картинкой.
 *
 * Причина ровно одна: адрес канала живёт в `src/content/landing.ts`, и его
 * правит заказчик. Приложенный файлом QR после такой правки молча начал бы
 * вести не туда — расхождение, которое никто не заметит, пока кто-нибудь не
 * наведёт телефон. Здесь код пересобирается из того же значения.
 *
 * `qrcode-generator` — зависимость времени сборки: в клиентский бандл она не
 * попадает, компонент зовёт эту функцию во frontmatter и отдаёт готовый путь.
 * Пакет без собственных зависимостей, MIT.
 */
import qrcode from 'qrcode-generator';

export interface QrCode {
  /** `d` для единственного <path>. Координаты — в модулях. */
  d: string;
  /** Сторона viewBox в модулях, вместе с зоной покоя. */
  size: number;
}

/**
 * @param quiet Зона покоя. Стандарт требует четыре модуля: без неё сканеры
 *   не находят код, если он вплотную к другому рисунку. Заложена в viewBox,
 *   чтобы отступ нельзя было случайно срезать вёрсткой.
 */
export function qrCode(data: string, quiet = 4): QrCode {
  // 0 — автоподбор версии; 'M' восстанавливает 15% и это обычный выбор для
  // экранного кода: 'L' экономит модули там, где грязи всё равно нет, но
  // теряет запас на блик и муар с матрицы.
  const qr = qrcode(0, 'M');
  qr.addData(data);
  qr.make();

  const n = qr.getModuleCount();
  let d = '';

  // Соседние тёмные модули склеиваются в один прямоугольник: помодульный
  // путь для версии 2 это ~200 команд, склеенный — вдвое короче, и рисуется
  // без волосяных швов между квадратами.
  for (let row = 0; row < n; row++) {
    let run = 0;
    for (let col = 0; col <= n; col++) {
      if (col < n && qr.isDark(row, col)) {
        run++;
        continue;
      }
      if (run) {
        d += `M${col - run + quiet} ${row + quiet}h${run}v1h-${run}z`;
        run = 0;
      }
    }
  }

  return { d, size: n + quiet * 2 };
}
